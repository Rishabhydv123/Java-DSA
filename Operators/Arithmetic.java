
public class Arithmetic {
    public static void main(String[] args ){
        // Binary
        int A = 15;
        int B =5;
        System.out.println("Summ :" +(A+B));
        System.out.println("Subb :" +(A-B));
        System.out.println("Mult :" +(A*B));
        System.out.println("Div :" +(A/B));
        System.out.println("mod :" +(A%B));
    }
    
}
