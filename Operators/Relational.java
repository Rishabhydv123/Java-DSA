
public class Relational {
    public static void main(String[] args) {
        int A = 10;
        int B = 5;
        System.err.println((A==B));
         System.err.println((A!=B));
         System.err.println((A>B));
         System.err.println((A<B));
         System.err.println((A>=B));
         System.err.println((A<=B));
    }
    
}
